/** Independent observations of the real Eclipse command registry and callback contracts. */
public class M3CommandRegistryContractTest {
    private static final class ExposedManager extends HandleObjectManager<Command> {
        Map<String, Command> identities() { return handleObjectsById; }
        Set<Command> definitions() { return definedHandleObjects; }
    }
    private static AbstractHandler handler(Object result) {
        return new AbstractHandler() {
            @Override public Object execute(ExecutionEvent event) { return result; }
        };
    }
    private static Category category(CommandManager manager) {
        Category category = manager.getCategory("category");
        category.define("Category", null);
        return category;
    }
    private static Command define(CommandManager manager, String id, Category category) {
        Command command = manager.getCommand(id);
        command.define(id, null, category, null);
        return command;
    }
    @Test void equalIdentifiersReuseEveryDomainHandle() {
        CommandManager manager = new CommandManager();
        // Aa and BB collide under String.hashCode; equal copies must preserve identity.
        for (String id : List.of("Aa", "BB", "AaAa", "BBBB", "AaBB", "BBAa")) {
            assertSame(manager.getCommand(id), manager.getCommand(new String(id)));
            assertSame(manager.getCategory(id), manager.getCategory(new String(id)));
            assertSame(manager.getParameterType(id), manager.getParameterType(new String(id)));
        }
        assertNotSame(manager.getCategory("Aa"), manager.getCategory("BB"));
        assertNotSame(manager.getParameterType("Aa"), manager.getParameterType("BB"));
        assertEquals(6, manager.getAllCommands().length);
        ContextManager contexts = new ContextManager();
        assertSame(contexts.getContext("Aa"), contexts.getContext(new String("Aa")));
    }
    @Test void growthPreservesIdentityAndSeparatesNamespaces() {
        CommandManager manager = new CommandManager();
        Category[] categories = new Category[4096];
        ParameterType[] types = new ParameterType[4096];
        for (int i = 0; i < categories.length; i++) {
            categories[i] = manager.getCategory("id." + i);
            types[i] = manager.getParameterType("id." + i);
        }
        for (int i = categories.length - 1; i >= 0; i--) {
            assertSame(categories[i], manager.getCategory("id." + i));
            assertSame(types[i], manager.getParameterType("id." + i));
        }
        assertEquals(0, manager.getAllCommands().length);
    }
    @Test void nullEmptyAndUncategorizedContractsRemainExact() {
        CommandManager manager = new CommandManager();
        assertEquals("A handle object may not have a null identifier",
                assertThrows(IllegalArgumentException.class, () -> manager.getCommand(null)).getMessage());
        assertEquals("The handle object must not have a zero-length identifier",
                assertThrows(IllegalArgumentException.class, () -> manager.getCommand("")).getMessage());
        assertThrows(IllegalArgumentException.class, () -> manager.getCategory(""));
        assertThrows(IllegalArgumentException.class, () -> manager.getParameterType(null));
        assertThrows(IllegalArgumentException.class, () -> manager.getParameterType(""));
        assertSame(manager.getCategory(null), manager.getCategory(CommandManager.AUTOGENERATED_CATEGORY_ID));
        assertThrows(NullPointerException.class, () -> manager.addExecutionListener(null));
        assertThrows(NullPointerException.class, () -> manager.removeExecutionListener(null));
        assertThrows(NullPointerException.class, () -> manager.setHandlersByCommandId(null));
    }
    @Test void categoryAndParameterDefinitionsExposeLiveReadOnlyViews() {
        CommandManager manager = new CommandManager();
        Set<?> categories = manager.getDefinedCategoryIds();
        Set<?> types = manager.getDefinedParameterTypeIds();
        List<String> events = new ArrayList<>();
        manager.addCommandManagerListener(event -> {
            if (event.isCategoryChanged()) events.add("category:" + event.getCategoryId() + ":" + event.isCategoryDefined());
            if (event.isParameterTypeChanged()) events.add("type:" + event.getParameterTypeId() + ":" + event.isParameterTypeDefined());
        });
        Category category = manager.getCategory("same");
        ParameterType type = manager.getParameterType("same");
        category.define("First", null);
        category.define("Renamed", "description");
        type.define("java.lang.String", null);
        assertEquals(Set.of("same"), categories);
        assertEquals(Set.of("same"), types);
        assertThrows(UnsupportedOperationException.class, categories::clear);
        assertThrows(UnsupportedOperationException.class, types::clear);
        assertSame(category, manager.getDefinedCategories()[0]);
        assertSame(type, manager.getDefinedParameterTypes()[0]);
        category.undefine();
        type.undefine();
        assertTrue(categories.isEmpty());
        assertTrue(types.isEmpty());
        assertSame(category, manager.getCategory(new String("same")));
        assertSame(type, manager.getParameterType(new String("same")));
        assertEquals(List.of("category:same:true", "type:same:true", "category:same:false", "type:same:false"), events);
    }
    @Test void commandSnapshotsAreDetachedAndRetainUndefinedIdentity() {
        CommandManager manager = new CommandManager();
        Category category = category(manager);
        Command command = define(manager, "defined", category);
        manager.getCommand("undefined");
        Set<?> ids = manager.getDefinedCommandIds();
        assertEquals(Set.of("defined"), ids);
        ids.clear();
        assertEquals(Set.of("defined"), manager.getDefinedCommandIds());
        Command[] all = manager.getAllCommands();
        Arrays.fill(all, null);
        assertEquals(Set.of(command, manager.getCommand("undefined")), new HashSet<>(Arrays.asList(manager.getAllCommands())));
        command.undefine();
        assertTrue(manager.getDefinedCommandIds().isEmpty());
        assertSame(command, manager.getCommand("defined"));
        assertEquals(2, manager.getAllCommands().length);
    }
    @Test void definitionCallbacksSeePublishedIdentityAndCanReenter() {
        CommandManager manager = new CommandManager();
        Category category = category(manager);
        List<String> events = new ArrayList<>();
        manager.addCommandManagerListener(event -> {
            if (!event.isCommandChanged()) return;
            String id = event.getCommandId();
            events.add(id);
            assertTrue(manager.getDefinedCommandIds().contains(id));
            assertSame(manager.getCommand(id), Arrays.stream(manager.getDefinedCommands())
                    .filter(command -> command.getId().equals(id)).findFirst().orElseThrow());
            if (id.equals("outer")) define(manager, "inner", category);
        });
        define(manager, "outer", category);
        assertEquals(List.of("outer", "inner"), events);
        assertEquals(Set.of("outer", "inner"), manager.getDefinedCommandIds());
    }
    private static final class ExecutionTrace implements IExecutionListener {
        final List<String> events = new ArrayList<>();
        @Override public void preExecute(String id, ExecutionEvent event) { events.add(id + ":pre"); }
        @Override public void postExecuteSuccess(String id, Object value) { events.add(id + ":success:" + value); }
        @Override public void postExecuteFailure(String id, ExecutionException failure) { events.add(id + ":failure"); }
        @Override public void notHandled(String id, NotHandledException failure) { events.add(id + ":unhandled"); }
        @Override public boolean equals(Object other) { return other instanceof ExecutionTrace; }
        @Override public int hashCode() { return 1; }
    }
    @Test void executionListenersUseIdentityAndCoverExistingAndFutureCommands() throws Exception {
        CommandManager manager = new CommandManager();
        Category category = category(manager);
        Command first = define(manager, "first", category);
        first.setHandler(handler("one"));
        ExecutionTrace left = new ExecutionTrace(), right = new ExecutionTrace();
        manager.addExecutionListener(left);
        manager.addExecutionListener(left);
        manager.addExecutionListener(right);
        Command second = define(manager, "second", category);
        second.setHandler(handler("two"));
        assertEquals("one", first.executeWithChecks(new ExecutionEvent()));
        assertEquals("two", second.executeWithChecks(new ExecutionEvent()));
        List<String> expected = List.of("first:pre", "first:success:one", "second:pre", "second:success:two");
        assertEquals(expected, left.events);
        assertEquals(expected, right.events);
        manager.removeExecutionListener(left);
        first.executeWithChecks(new ExecutionEvent());
        assertEquals(4, left.events.size());
        assertEquals(6, right.events.size());
        manager.removeExecutionListener(right);
        second.executeWithChecks(new ExecutionEvent());
        assertEquals(6, right.events.size());
    }
    @Test void bulkHandlerCallbacksPreserveObservedCrossCommandState() {
        CommandManager manager = new CommandManager();
        Command z = manager.getCommand("z"); // Deliberately inserted before a.
        Command a = manager.getCommand("a");
        IHandler aHandler = handler("a"), zHandler = handler("z");
        List<Boolean> observations = new ArrayList<>();
        z.addCommandListener(event -> {
            if (event.isHandledChanged()) observations.add(a.getHandler() == aHandler);
        });
        manager.setHandlersByCommandId(Map.of("a", aHandler, "z", zHandler));
        // Independent hand-checked current baseline: a is updated before z's callback.
        assertEquals(List.of(true), observations);
        assertSame(aHandler, a.getHandler());
        assertSame(zHandler, z.getHandler());
    }
    @Test void bulkHandlerCallbacksRetainFailureAndReentrantMutationEffects() {
        CommandManager manager = new CommandManager();
        manager.getCommand("z");
        Command a = manager.getCommand("a");
        a.addCommandListener(event -> {
            if (event.isHandledChanged()) manager.getCommand("new");
        });
        assertThrows(ConcurrentModificationException.class,
                () -> manager.setHandlersByCommandId(Map.of("a", handler("a"), "z", handler("z"))));
        assertSame(manager.getCommand("new"), manager.getCommand(new String("new")));
        assertNull(manager.getCommand("z").getHandler());
        manager.setHandlersByCommandId(Collections.emptyMap());
        assertNull(a.getHandler());
    }
    @Test void protectedRegistryFieldsRetainTypeModifiersAndBackedViews() throws Exception {
        Field identities = HandleObjectManager.class.getDeclaredField("handleObjectsById");
        Field definitions = HandleObjectManager.class.getDeclaredField("definedHandleObjects");
        assertEquals(Map.class, identities.getType());
        assertEquals(Set.class, definitions.getType());
        assertEquals(Modifier.PROTECTED | Modifier.FINAL, identities.getModifiers());
        assertEquals(Modifier.PROTECTED | Modifier.FINAL, definitions.getModifiers());
        ExposedManager manager = new ExposedManager();
        CommandManager commands = new CommandManager();
        Command a = commands.getCommand("a");
        manager.identities().put("a", a);
        Collection<Command> values = manager.identities().values();
        manager.identities().put("b", commands.getCommand("b"));
        assertEquals(2, values.size());
        assertTrue(values.remove(a));
        assertFalse(manager.identities().containsKey("a"));
        Iterator<String> iterator = manager.identities().keySet().iterator();
        manager.identities().put("c", commands.getCommand("c"));
        assertThrows(ConcurrentModificationException.class, iterator::next);
    }
    @Test void helpContextLifetimeRemainsWeakAndOverridesAreReversible() throws Exception {
        CommandManager manager = new CommandManager();
        Field field = CommandManager.class.getDeclaredField("helpContextIdsByHandler");
        field.setAccessible(true);
        assertInstanceOf(WeakHashMap.class, field.get(manager));
        Category category = category(manager);
        Command command = define(manager, "help", category);
        IHandler handler = handler("done");
        command.setHandler(handler);
        manager.setHelpContextId(handler, "help.id");
        assertEquals("help.id", manager.getHelpContextId(command));
        manager.setHelpContextId(handler, null);
        assertNull(manager.getHelpContextId(command));
        assertThrows(NullPointerException.class, () -> manager.setHelpContextId(null, "bad"));
    }
    @Test @Tag("density") void categoryAndParameterIdentityStorageRetainsNoEntryPerHandle() throws Exception {
        CommandManager manager = new CommandManager();
        for (int i = 0; i < 4096; i++) {
            manager.getCategory("entry." + i);
            manager.getParameterType("entry." + i);
        }
        for (String name : List.of("categoriesById", "parameterTypesById")) {
            Field field = CommandManager.class.getDeclaredField(name);
            field.setAccessible(true);
            assertEquals(0, retainedEntries(field.get(manager)),
                    name + " must own slots, not one retained Map.Entry object per identity");
        }
    }
    private static int retainedEntries(Object owner) throws Exception {
        Set<Object> seen = Collections.newSetFromMap(new IdentityHashMap<>());
        ArrayDeque<Object> pending = new ArrayDeque<>();
        pending.add(owner);
        int entries = 0;
        while (!pending.isEmpty()) {
            Object value = pending.removeFirst();
            if (!seen.add(value)) continue;
            Class<?> type = value.getClass();
            if (value instanceof Map.Entry<?, ?>) entries++;
            if (type.isArray()) {
                if (!type.getComponentType().isPrimitive()) {
                    for (Object child : (Object[]) value) if (child != null && ownedStructure(child)) pending.add(child);
                }
            } else {
                for (Class<?> current = type; current != Object.class; current = current.getSuperclass()) {
                    if (current == AbstractMap.class) continue; // Its view caches do not own registry payload.
                    for (Field field : current.getDeclaredFields()) {
                        if (Modifier.isStatic(field.getModifiers()) || field.getType().isPrimitive()) continue;
                        field.setAccessible(true);
                        Object child = field.get(value);
                        if (child != null && ownedStructure(child)) pending.add(child);
                    }
                }
            }
        }
        return entries;
    }
    private static boolean ownedStructure(Object value) {
        String name = value.getClass().getName();
        return value.getClass().isArray() || value instanceof Map.Entry<?, ?> ||
                name.startsWith("java.util.HashMap") || name.startsWith("org.eclipse.core.internal.commands.m3.");
    }
}
